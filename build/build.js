/* build/build.js — index.html is GENERATED, never hand-edited.
   Every <script id="mom-*"> block is injected verbatim from api/. That is the
   mirroring law expressed as a build step instead of a discipline: an edit to
   api/ cannot fail to reach the browser, because the browser file does not
   exist until this runs. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const MAP = require('./modules.json');
const CONFIGS = require('./configs.json');

/* The bundled Config Docs, read from config/ and emitted as one JS object.

   They used to live twice: once as config/<industry>-demo-config.csv and once
   as a 45,000-character string literal in shell.html. Nothing kept the two in
   step, which is how Release 3's finding D happened. Generating the literal
   from the files makes the CSV the only copy — the object the browser reads
   does not exist until this runs, so it cannot fall behind.

   Every string is emitted with JSON.stringify, so a quote, a newline or an
   em dash in a document is escaped by the language rather than by hand. */
function demoConfigs() {
  const keys = Object.keys(CONFIGS).filter(function (k) { return k.charAt(0) !== '_'; }).sort();
  const rows = keys.map(function (industry) {
    const file = path.join(ROOT, 'config', CONFIGS[industry]);
    if (!fs.existsSync(file)) throw new Error('config missing for ' + industry + ': ' + CONFIGS[industry]);
    const csv = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    return '  ' + JSON.stringify(industry) + ': ' + JSON.stringify(csv) + ',';
  });
  return '/* GENERATED by build/build.js from config/ — do not edit here.\n' +
    '   Source of truth: the CSV files listed in build/configs.json. */\n' +
    'const DEMO_CONFIG = {\n' + rows.join('\n') + '\n};';
}

function build() {
  let html = fs.readFileSync(path.join(ROOT, 'src', 'shell.html'), 'utf8');

  const cfgMarker = '<!--mom:demo-configs-->';
  if (html.indexOf(cfgMarker) < 0) throw new Error('shell.html has no slot for: demo-configs');
  html = html.replace(cfgMarker, demoConfigs());

  const missing = [];
  Object.keys(MAP).forEach(function (file) {
    const id = MAP[file];
    const src = fs.readFileSync(path.join(ROOT, 'api', file), 'utf8').replace(/\r\n/g, '\n').trim();
    const marker = '<!--mom:inject ' + id + '-->';
    if (html.indexOf(marker) < 0) { missing.push(id); return; }
    html = html.replace(marker, '<script id="' + id + '">\n' + src + '\n</script>');
  });
  if (missing.length) throw new Error('shell.html has no slot for: ' + missing.join(', '));
  const left = html.match(/<!--mom:inject [^>]*-->/g);
  if (left) throw new Error('unfilled slots: ' + left.join(', '));

  const bootPath = path.join(ROOT, 'src', 'boot.js');
  if (fs.existsSync(bootPath) && html.indexOf('<!--mom:boot-->') >= 0) {
    html = html.replace('<!--mom:boot-->',
      '<script id="mom-boot">\n' + fs.readFileSync(bootPath, 'utf8').trim() + '\n</script>');
  }
  const out = path.join(ROOT, 'public');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'index.html'), html);
  return html;
}
if (require.main === module) {
  const h = build();
  console.log('public/index.html · ' + (h.length / 1048576).toFixed(2) + ' MB · ' +
    Object.keys(MAP).length + ' modules inlined · ' +
    Object.keys(CONFIGS).filter(function (k) { return k.charAt(0) !== '_'; }).length +
    ' config docs generated');
}
module.exports = build;
